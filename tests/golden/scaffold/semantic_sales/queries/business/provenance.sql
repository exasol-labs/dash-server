SELECT m.MODEL_NAME, m.VERSION_NUMBER, vr.VALIDATION_RUN_ID, vr.STATUS AS VALIDATION_STATUS,
       vr.ERROR_COUNT, vr.WARNING_COUNT, vr.FINISHED_AT
FROM SEMANTIC_AGENT.MODELS_FOR_AGENT m
LEFT JOIN (SELECT MODEL_ID, VERSION_ID, MAX(VALIDATION_RUN_ID) AS VALIDATION_RUN_ID
           FROM SEMANTIC_SOURCE.VALIDATION_RUNS
           WHERE STATUS <> 'RUNNING'
           GROUP BY MODEL_ID, VERSION_ID) latest
  ON latest.MODEL_ID = m.MODEL_ID AND latest.VERSION_ID = m.VERSION_ID
LEFT JOIN SEMANTIC_SOURCE.VALIDATION_RUNS vr ON vr.VALIDATION_RUN_ID = latest.VALIDATION_RUN_ID
WHERE m.MODEL_NAME = 'sales'
